"""The document registry and the schemas built from it.

`documents.json` is generated by the frontend's build script and committed, so
these tests are the backend's half of the contract: that the file it was handed
is usable, and that the LLM schema built from it names exactly the fields the
chosen agreement declares.
"""

from __future__ import annotations

import json

import pytest
from fastapi.testclient import TestClient

from app.chat.documents import DOCUMENTS_FILE, all_documents, get_document
from app.chat.models import turn_model


def test_loads_every_agreement() -> None:
    assert len(all_documents()) == 11


def test_every_document_is_usable() -> None:
    for document in all_documents():
        assert document.slug
        assert document.name
        assert len(document.parties) == 2
        assert document.fields, f"{document.slug} declares no fields"
        for field in document.fields:
            # Without a question the assistant reads the legal variable name
            # aloud, which is the experience the chat exists to avoid.
            assert field.ask, f"{document.slug}.{field.key} has no question"
            assert field.label


def test_field_keys_are_unique_within_a_document() -> None:
    for document in all_documents():
        keys = [field.key for field in document.fields]
        assert len(set(keys)) == len(keys), document.slug


def test_looks_a_document_up_by_slug() -> None:
    assert get_document("mutual-nda").name.startswith("Mutual Non-Disclosure")


def test_an_unknown_slug_is_simply_absent() -> None:
    assert get_document("employment-contract") is None


def test_the_empty_slug_means_nothing_chosen_yet() -> None:
    assert get_document("") is None


def test_stays_in_step_with_the_frontends_generated_copy() -> None:
    # One generator writes both halves; if this file were edited by hand the
    # assistant would fill in fields the browser does not render.
    payload = json.loads(DOCUMENTS_FILE.read_text(encoding="utf-8"))
    assert "do not edit" in payload["_generated"]
    assert len(payload["documents"]) == len(all_documents())


@pytest.mark.parametrize("document", all_documents(), ids=lambda d: d.slug)
def test_the_schema_names_exactly_that_documents_fields(document) -> None:
    schema = turn_model(document)
    updates = schema.model_fields["updates"].annotation

    assert set(updates.model_fields) == set(document.field_keys)


@pytest.mark.parametrize("document", all_documents(), ids=lambda d: d.slug)
def test_every_schema_can_be_serialised_for_structured_outputs(document) -> None:
    # LiteLLM turns this into the JSON schema the provider enforces; a model
    # that cannot produce one would fail at request time, not here.
    schema = turn_model(document).model_json_schema()

    assert "reply" in schema["properties"]
    assert "documentType" in schema["properties"]


def test_the_undecided_schema_offers_every_agreements_fields() -> None:
    # The turn that settles the document is the same turn that hears the first
    # answers, so the schema before one is chosen has to be able to hold them.
    updates = turn_model(None).model_fields["updates"].annotation
    every_key = {key for document in all_documents() for key in document.field_keys}

    assert set(updates.model_fields) == every_key


def test_a_schema_is_built_once_and_reused() -> None:
    assert turn_model(get_document("mutual-nda")) is turn_model(
        get_document("mutual-nda")
    )


def test_documents_endpoint_lists_the_catalogue(client: TestClient) -> None:
    response = client.get("/api/documents")

    assert response.status_code == 200
    body = response.json()
    assert len(body) == 11
    assert {"slug", "name", "description", "limitation"} <= set(body[0])


def test_documents_endpoint_states_the_known_limits(client: TestClient) -> None:
    body = client.get("/api/documents").json()
    psa = next(row for row in body if row["slug"] == "professional-services-agreement")

    assert "statement of work" in psa["limitation"].lower()


def test_documents_endpoint_needs_no_api_key(unconfigured_client: TestClient) -> None:
    # The catalogue is not the assistant; browsing it must work regardless.
    assert unconfigured_client.get("/api/documents").status_code == 200
