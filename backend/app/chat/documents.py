"""The catalogue of agreements the assistant can draft.

Loaded from `documents.json`, which is generated by
`frontend/scripts/build-documents.mjs` from the repository's templates/ and
hints.json. The backend deliberately does not parse the markdown itself: a
second parser would drift from the one the frontend uses, and the failure mode
of that drift is the assistant filling in a field name nothing renders.

The file is committed, so the backend runs from a checkout or a container
without needing Node.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

DOCUMENTS_FILE = Path(__file__).resolve().parent / "documents.json"


@dataclass(frozen=True)
class Field:
    """One value the user has to supply for an agreement."""

    key: str
    """camelCase; the name shared by the LLM schema, the API and the renderer."""

    label: str
    """The variable's name as the agreement writes it, e.g. "Target Uptime"."""

    group: str
    ask: str
    """The question to ask, in plain language, from hints.json."""

    type: str
    required: bool
    caption: str | None = None
    options: tuple[str, ...] = ()


@dataclass(frozen=True)
class Document:
    slug: str
    name: str
    description: str
    parties: tuple[str, str]
    """The two role names the agreement calls its parties, e.g. Customer/Provider."""

    fields: tuple[Field, ...]
    groups: tuple[str, ...]
    limitation: str | None = None
    """Where the product knowingly does less than the agreement allows."""

    def field(self, key: str) -> Field | None:
        return next((field for field in self.fields if field.key == key), None)

    @property
    def field_keys(self) -> tuple[str, ...]:
        return tuple(field.key for field in self.fields)


def _build(raw: dict) -> Document:
    parties = raw["parties"]
    return Document(
        slug=raw["slug"],
        name=raw["name"],
        description=raw["description"],
        parties=(parties[0], parties[1]),
        fields=tuple(
            Field(
                key=field["key"],
                label=field["label"],
                group=field["group"],
                ask=field["ask"],
                type=field.get("type", "text"),
                required=field.get("required", False),
                caption=field.get("caption"),
                options=tuple(field.get("options", ())),
            )
            for field in raw["fields"]
        ),
        groups=tuple(raw.get("groups", ())),
        limitation=raw.get("limitation"),
    )


@lru_cache(maxsize=1)
def load_documents() -> dict[str, Document]:
    """Every supported agreement, keyed by slug, in catalogue order."""
    try:
        payload = json.loads(DOCUMENTS_FILE.read_text(encoding="utf-8"))
    except FileNotFoundError as error:  # pragma: no cover - a broken checkout
        raise RuntimeError(
            f"{DOCUMENTS_FILE} is missing. It is generated by "
            "frontend/scripts/build-documents.mjs and committed; run "
            "`npm run build:documents` in frontend/ to recreate it."
        ) from error

    documents = [_build(entry) for entry in payload["documents"]]
    if not documents:
        raise RuntimeError(f"{DOCUMENTS_FILE} lists no documents.")

    return {document.slug: document for document in documents}


def get_document(slug: str) -> Document | None:
    """The document with this slug, or None -- including for the empty slug."""
    return load_documents().get(slug)


def all_documents() -> list[Document]:
    return list(load_documents().values())
